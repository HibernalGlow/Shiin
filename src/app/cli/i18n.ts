const dictionaries: Record<Language, Messages> = { zh, en }

export type Translator = (key: Key, values?: Record<string, string | number>) => string

export function createTranslator(language: Language): Translator {
  const messages = dictionaries[language] ?? zh
  return (key, values) => {
    const template = messages[key] ?? key
    if (!values) return template
    return template.replace(/\{(\w+)\}/g, (_, name: string) => String(values[name] ?? `{${name}}`))
  }
}

/** `--lang` / `SHIIN_LANG` / `LC_ALL` 依次收敛成 `zh` 或 `en`；默认中文。 */
export function resolveLanguage(requested?: string, env: Record<string, string | undefined> = {}): Language {
  const candidates = [requested, env.SHIIN_LANG, env.LC_ALL, env.LANG]
  for (const candidate of candidates) {
    const value = candidate?.trim().toLowerCase()
    if (!value) continue
    if (value.startsWith('zh')) return 'zh'
    if (value.startsWith('en')) return 'en'
  }
  return 'zh'
}
